// formatEmotionDirective 把 Planner 已决定的情绪转成一行「表演指令」注入 Replyer。
//
// 背景：Planner 负责决定情绪（它早于流式 TTS，供前端驱动表情），而 Replyer 才写台词。
// 此前 Replyer 的提示词只给了情绪取值范围并要求「让每句情绪匹配内容」，却没告诉它
// **本轮该是什么情绪**——于是 LLM 只能逐句重新猜，容易出现「说的内容和该有的情绪对不上」
// 或情绪与前端表情不一致。这里把 Planner 的决定显式传给 Replyer，让台词与情绪对齐。
//
// 只有当 Planner 确实给出了情绪时才注入，避免产生空指令行。
func formatEmotionDirective(decision PlannerDecision) string {
	emotion := strings.TrimSpace(decision.Emotion)
	if emotion == "" {
		return ""
	}
	directive := fmt.Sprintf("\nperformance_directive: 本轮整体情绪为 %q", emotion)
	if mood := strings.TrimSpace(decision.Mood); mood != "" {
		directive += fmt.Sprintf("，基调 %q", mood)
	}
	// 用自然语言描述连续维度，比裸数字更利于模型把握语气。
	var hints []string
	if decision.Valence >= 0.35 {
		hints = append(hints, "偏积极")
	} else if decision.Valence <= -0.35 {
		hints = append(hints, "偏消极")
	}
	if decision.Energy >= 0.7 {
		hints = append(hints, "情绪激动")
	} else if decision.Energy > 0 && decision.Energy <= 0.3 {
		hints = append(hints, "语气平静")
	}
	if decision.Dominance >= 0.5 {
		hints = append(hints, "自信主导")
	} else if decision.Dominance <= -0.5 {
		hints = append(hints, "顺从害羞")
	}
	if len(hints) > 0 {
		directive += "（" + strings.Join(hints, "、") + "）"
	}
	return directive + "。台词的用词与语气要与该情绪一致，不要写出与情绪相悖的台词。"
}

func QueryPlannerMemory(ctx context.Context, memorySvc *memory.ServiceMemory, snapshot TurnSnapshot, decision PlannerDecision) ([]string, error) {
	if memorySvc == nil {
		return nil, nil
	}
	query := strings.TrimSpace(decision.MemoryQuery)
	if query == "" {
		query = snapshot.Target.Content
	}
	memories, err := memorySvc.SearchMemories(ctx, "", "", query, 8)
	if err != nil {
		return nil, fmt.Errorf("query memory: %w", err)
	}
	result := make([]string, 0, len(memories))
	for _, item := range memories {
		result = append(result, fmt.Sprintf("%s/%s: %s", item.Scope, item.Kind, item.Text))
	}
	return result, nil
}

func ExecutePlannerTools(ctx context.Context, tools []tool.BaseTool, calls []PlannerToolCall) ([]ToolResult, error) {
	if len(calls) == 0 {
		return nil, nil
	}
	toolMap := make(map[string]tool.BaseTool)
	for _, item := range tools {
		info, err := item.Info(ctx)
		if err != nil {
			return nil, fmt.Errorf("get tool info: %w", err)
		}
		toolMap[info.Name] = item
	}

	results := make([]ToolResult, 0, len(calls))
	for _, call := range calls {
		item, ok := toolMap[call.Name]
		if !ok {
			return nil, fmt.Errorf("planner requested unknown tool %q", call.Name)
		}
		invokable, ok := item.(tool.InvokableTool)
		if !ok {
			return nil, fmt.Errorf("planner requested non-invokable tool %q", call.Name)
		}
		args, err := json.Marshal(call.Arguments)
		if err != nil {
			return nil, fmt.Errorf("marshal tool arguments for %q: %w", call.Name, err)
		}
		output, err := invokable.InvokableRun(ctx, string(args))
		if err != nil {
			return nil, fmt.Errorf("execute tool %q: %w", call.Name, err)
		}
		results = append(results, ToolResult{Name: call.Name, Result: output})
	}
	return results, nil
}

func extractJSONObject(content string) string {
	text := strings.TrimSpace(content)
	text = strings.TrimPrefix(text, "```json")
	text = strings.TrimPrefix(text, "```")
	text = strings.TrimSuffix(text, "```")
	text = strings.TrimSpace(text)
	start := strings.Index(text, "{")
	end := strings.LastIndex(text, "}")
	if start >= 0 && end >= start {
		return text[start : end+1]
	}
	return text
}

func formatPending(messages []NormalizedMessage) string {
	lines := make([]string, 0, len(messages))
	for _, msg := range messages {
		lines = append(lines, fmt.Sprintf("- id=%s sender=%s content=%s", msg.ID, nonEmptyString(msg.SenderName, msg.SenderID), msg.Content))
	}
	return strings.Join(lines, "\n")
}

func formatHistory(messages []*schema.Message, limit int) string {
	if limit > 0 && len(messages) > limit {
		messages = messages[len(messages)-limit:]
	}
	lines := make([]string, 0, len(messages))
	for _, msg := range messages {
		if strings.TrimSpace(msg.Content) == "" {
			continue
		}
		lines = append(lines, fmt.Sprintf("%s: %s", msg.Role, strings.TrimSpace(msg.Content)))
	}
	return strings.Join(lines, "\n")
}

func formatStringList(values []string) string {
	if len(values) == 0 {
		return "(none)"
	}
	lines := make([]string, 0, len(values))
	for _, value := range values {
		lines = append(lines, "- "+value)
	}
	return strings.Join(lines, "\n")
}

// formatAvailableTools 把当前可调用的工具渲染成 Prompt 里的清单（名称 + 一句话说明）。
// 会包含插件注册的工具（如 run_agent），让 Planner 知道可以用它们。
func formatAvailableTools(ctx context.Context, tools []tool.BaseTool) string {
	if len(tools) == 0 {
		return "(no tools available)"
	}
	lines := make([]string, 0, len(tools))
	for _, t := range tools {
		info, err := t.Info(ctx)
		if err != nil {
			continue
		}
		desc := strings.ReplaceAll(info.Desc, "\n", " ")
		lines = append(lines, fmt.Sprintf("- %s: %s", info.Name, desc))
	}
	if len(lines) == 0 {
		return "(no tools available)"
	}
	return strings.Join(lines, "\n")
}

// toolNames 返回一组工具的简单名字列表（用于日志/诊断，不依赖真实上下文）。
func toolNames(tools []tool.BaseTool) []string {
	names := make([]string, 0, len(tools))
	for _, t := range tools {
		if info, err := t.Info(context.Background()); err == nil {
			names = append(names, info.Name)
		}
	}
	return names
}

// codingToolName 返回可用工具里的编码 agent 工具名（如 "run_agent"），找不到返回 "(none)"。
func codingToolName(ctx context.Context, tools []tool.BaseTool) string {
	for _, t := range tools {
		info, err := t.Info(ctx)
		if err != nil {
			continue
		}
		nm := strings.ToLower(info.Name)
		desc := strings.ToLower(info.Desc)
		if strings.Contains(nm, "agent") || strings.Contains(nm, "code") || strings.Contains(nm, "claude") || strings.Contains(nm, "codex") ||
			strings.Contains(desc, "coding agent") || strings.Contains(desc, "编码 agent") {
			return info.Name
		}
	}
	return "(none)"
}

// codingToolHint 返回用于提示 Planner 的编码 agent 措辞（复用 codingToolName 的检测）。
func codingToolHint(ctx context.Context, tools []tool.BaseTool) string {
	if name := codingToolName(ctx, tools); name != "(none)" {
		return fmt.Sprintf("the coding-agent tool %q", name)
	}
	return "no coding-agent tool is available"
}

func formatToolResults(values []ToolResult) string {
	if len(values) == 0 {
		return "(none)"
	}
	lines := make([]string, 0, len(values))
	for _, value := range values {
		lines = append(lines, fmt.Sprintf("- %s: %s", value.Name, value.Result))
	}
	return strings.Join(lines, "\n")
}

func nonEmptyString(value, fallback string) string {
	if strings.TrimSpace(value) != "" {
		return strings.TrimSpace(value)
	}
	return fallback
}
