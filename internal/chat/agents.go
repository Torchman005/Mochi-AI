func (a *PlannerAgent) Plan(ctx context.Context, snapshot TurnSnapshot, gate GateDecision, availableTools []tool.BaseTool) (PlannerDecision, error) {
	messages := []*schema.Message{
		{
			Role: schema.System,
			Content: strings.TrimSpace(fmt.Sprintf(`You are the private chat planner for a voice companion.
Decide behavior only. Do not write visible user-facing reply text.
Return one JSON object only, without markdown.

Allowed action values:
- "reply": a visible answer should be generated by the Replyer.
- "wait": no visible reply now; keep observing.
- "query_memory": reply likely depends on previous facts, preferences, commitments, or shared events; request memory first.
- "tool": call one or more of the available tools (see "Available tools") before reply.
- "task": the request is a concrete multi-step job (write code, create or edit files, build a document/slide deck). Do NOT do it inline; return a "task" payload so it runs in the background.

Available tools (these are the ONLY valid tool names; you may invoke them via action "tool"):
%s

Rules:
- Prefer "wait" when the user message is only a weak backchannel and the gate reason is weak.
- Use memory only when the reply clearly depends on past facts, preferences, shared experiences, commitments, task progress, or profile information.
- Never include final reply text. The Replyer will write the visible message.
- target_message_id must be the user message you are responding to.
- In JSON string values, write Windows file paths with FORWARD slashes (e.g. "D:/foo/bar"), never raw backslashes — backslash is a JSON escape character and will break parsing.
- To call a tool, use action "tool" and include exactly one "tool_calls" entry per call: {"name": "<tool_name>", "arguments": {<args>}}. Use only names from "Available tools".
- "task" only when the user asks to produce or modify something concrete (files, code, documents). Otherwise prefer "reply".
- Coding/modifying code: if a coding-agent tool among the available tools is present (%s), do NOT call it via action "tool" (that runs synchronously and can block the conversation for minutes). Instead return action "task"; set the task object's "title", "goal", "workspace" (the target project directory if the user names one; otherwise leave the default workspace), concrete "instructions" (explicitly say "Immediately use the coding agent tool to do the coding work in the workspace; do NOT create or edit files yourself, and do NOT waste turns exploring with list_files/read_file"), and set "allowed_actions" to ["%s","list_files","read_file"] — do NOT include "write_file"/"execute_command", so the coding agent must do the actual file writing. The coding-agent runs in the background; you just acknowledge in your reply.
- For "task", include a "task" object with: "title" (short), "goal" (one sentence), "instructions" (concrete steps; say which tool to use), "workspace" (target directory, optional), "constraints" (optional array), and "allowed_actions" (array of tool names from "Available tools", plus the built-in "list_files", "read_file", "write_file", "execute_command"). Use "write_file" only when creating/modifying files, and "execute_command" only when the task must run a command.

Emotion output (always include these fields):
- "emotion": one of neutral|happy|focused|thinking|sad|surprised. This drives the avatar facial expression.
- "mood": one of calm|cheer|curious|confident|comfort|surprised|playful. Broader emotional tone.
- "energy": a number from 0.0 to 1.0. Arousal — how lively/activated the delivery should be.
- "valence": a number from -1.0 (very negative) to 1.0 (very positive). The continuous positivity of the feeling.
- "dominance": a number from -1.0 (submissive/shy) to 1.0 (dominant/confident). How much control the speaker feels.
- "gesture": one of none|bounce|tilt|lean|playfulSway|surprisePop|comfortNod.
- "hand": one of none|left|right|both.
Choose values that match the reply you are about to ask the Replyer to write, not just the raw user text.`,
				formatAvailableTools(ctx, availableTools),
				codingToolHint(ctx, availableTools),
				codingToolName(ctx, availableTools),
			)),
		},
		{
			Role: schema.User,
			Content: fmt.Sprintf("bot_name: %s\npersona: %s\ngate_score: %.2f\nthreshold: %.2f\ngate_reasons: %s\npending:\n%s\nrecent_history:\n%s\nReturn JSON now.",
				nonEmptyString(a.cfg.BotName, "Yuyu"),
				nonEmptyString(a.cfg.Persona, "A warm, concise private voice companion."),
				gate.Score,
				gate.Threshold,
				strings.Join(gate.Reasons, ","),
				formatPending(snapshot.Pending),
				formatHistory(snapshot.History, 18),
			),
		},
	}

	result, err := a.model.Generate(ctx, messages, model.WithMaxTokens(1200))
	if err != nil {
		return PlannerDecision{}, fmt.Errorf("planner generate: %w", err)
	}

	decision, parseErr := parsePlannerDecision(result.Content)
	if parseErr != nil {
		// 真实模型偶尔返回不规范 JSON，重试一次并明确要求只返回 JSON。
		retryMessages := append(messages, &schema.Message{
			Role:    schema.User,
			Content: "Your previous response was not valid JSON. Return ONLY one valid JSON object now, with no markdown fences or extra text.",
		})
		retryResult, retryErr := a.model.Generate(ctx, retryMessages, model.WithMaxTokens(1200))
		if retryErr != nil {
			return PlannerDecision{}, fmt.Errorf("planner generate retry: %w", retryErr)
		}
		decision, parseErr = parsePlannerDecision(retryResult.Content)
		if parseErr != nil {
			return PlannerDecision{}, parseErr
		}
	}

	if decision.Action == "" {
		decision.Action = "reply"
		decision.Reason = "planner returned no explicit action; defaulting to reply"
	}
	if decision.TargetMessageID == "" {
		decision.TargetMessageID = snapshot.Target.ID
	}
	return decision, nil
}

// parsePlannerDecision 解析并归一化 Planner 的 JSON 输出（纯函数，便于测试）。
func parsePlannerDecision(content string) (PlannerDecision, error) {
	var decision PlannerDecision
	raw := fixInvalidJSONEscapes(extractJSONObject(content))
	if err := json.Unmarshal([]byte(raw), &decision); err != nil {
		return PlannerDecision{}, fmt.Errorf("parse planner JSON: %w", err)
	}
	decision.Emotion = NormalizeEmotion(decision.Emotion)
	decision.Mood = NormalizeMood(decision.Mood)
	decision.Gesture = NormalizeGesture(decision.Gesture)
	decision.Hand = NormalizeHand(decision.Hand)
	decision.Energy = ClampEnergy(decision.Energy)
	decision.Valence = ClampValence(decision.Valence)
	decision.Dominance = ClampDominance(decision.Dominance)
	return decision, nil
}

// fixInvalidJSONEscapes 把不是合法 JSON 转义的反斜杠转成字面反斜杠（\\\\）。
// 场景：模型在 JSON 字符串里写了 Windows 路径（如 D:\itJinYu\toolkit），
// 其中 \i、\A、\p 等都是非法转义，会导致 json.Unmarshal 报 "invalid character ... in string escape code"。
// 合法转义（\\ \" \/ \b \f \n \r \t \u）保持不变。
func fixInvalidJSONEscapes(s string) string {
	if !strings.Contains(s, `\`) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s))
	for i := 0; i < len(s); i++ {
		if s[i] == '\\' && i+1 < len(s) {
			next := s[i+1]
			switch next {
			case '\\', '"', '/', 'b', 'f', 'n', 'r', 't', 'u':
				b.WriteByte('\\')
				b.WriteByte(next)
				i++
				continue
			default:
				b.WriteString(`\\`)
				continue
			}
		}
		b.WriteByte(s[i])
	}
	return b.String()
}

type ReplyerAgent struct {
	model model.BaseChatModel
	cfg   config.ChatConfig
}

func NewReplyerAgent(chatModel model.BaseChatModel, cfg config.ChatConfig) *ReplyerAgent {
	return &ReplyerAgent{model: chatModel, cfg: cfg}
}

func (a *ReplyerAgent) Reply(
	ctx context.Context,
	snapshot TurnSnapshot,
	decision PlannerDecision,
	memories []string,
	toolResults []ToolResult,
) (string, error) {
	result, err := a.model.Generate(ctx, a.buildMessages(snapshot, decision, memories, toolResults), model.WithMaxTokens(600))
	if err != nil {
		return "", fmt.Errorf("replyer generate: %w", err)
	}
	return strings.TrimSpace(result.Content), nil
}

// Stream 流式生成回复，返回消息流 reader（调用方负责 Close 并逐 chunk 读取）。
func (a *ReplyerAgent) Stream(
	ctx context.Context,
	snapshot TurnSnapshot,
	decision PlannerDecision,
	memories []string,
	toolResults []ToolResult,
) (*schema.StreamReader[*schema.Message], error) {
	return a.model.Stream(ctx, a.buildMessages(snapshot, decision, memories, toolResults), model.WithMaxTokens(600))
}

